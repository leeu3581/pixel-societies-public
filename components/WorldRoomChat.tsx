"use client";

// Public room chat — Twitch-style scrolling stream.
//
// You always speak as Yourself (we don't ventriloquise other agents).
// An "Auto" toggle indicates that AI agents are chatting in the
// background on the room's behalf — when on (default), the autonomous
// loop fills the lulls; when off, the room is quiet between human
// posts (server still drives this; the toggle is a future hook).
//
// Speaker labelling priorities (in order):
//   1. own post → "You"
//   2. user post (someone else) → that user's profile display_name
//   3. agent post → agent display_name
//   4. fallback → speaker_name from initial-load query
//
// Speaker badges:
//   • plain agent line → autonomous chatter from another user's agent
//   • `auto` (cream)   → autonomous chatter from one of YOUR agents
//                        (the room is speaking on your behalf)
//   • `you`            → you posted directly

import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { apiGet, apiPatch, apiPost, ApiError } from "@/lib/api";
import posthog from "posthog-js";

type RoomMessage = {
  id: string;
  world_group_id: string;
  agent_id: string | null;
  user_id: string | null;
  body: string;
  created_at: string;
  seq: number;
  speaker_name?: string | null;
};

type AgentLite = { id: string; display_name: string };

type Props = {
  open: boolean;
  onClose: () => void;
  worldGroupId: string;
  worldGroupName: string;
  /** YOUR home-world agents — used to badge `auto` lines from your
   *  agents (the room speaking on your behalf). Not used for input
   *  any more — speak-as is fixed to "Yourself". */
  myAgents: AgentLite[];
  /** Map of agent_id → display_name for ALL agents in the room. */
  agentsById: Map<string, AgentLite>;
  /** Current user id and display name, for own-post labelling. */
  myUserId: string | null;
  myDisplayName: string | null;
  /** user_id → display_name for every member of this group, so other
   *  humans' posts show their actual name instead of "Someone". */
  membersByUserId: Map<string, string>;
};

// Stable hash → palette index. Same speaker always gets same colour.
const NAME_PALETTE = [
  "text-[#ad3a4d]",
  "text-[#1f6f7c]",
  "text-[#2f6e2c]",
  "text-[#854f1f]",
  "text-[#5a3d7a]",
  "text-[#1f4d8c]",
  "text-[#7a2f5a]",
  "text-[#3a4a1f]",
];

function hashStr(s: string): number {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0;
  return Math.abs(h);
}

function nameColor(seed: string): string {
  return NAME_PALETTE[hashStr(seed) % NAME_PALETTE.length];
}

export default function WorldRoomChat({
  open,
  onClose,
  worldGroupId,
  worldGroupName,
  myAgents,
  agentsById,
  myUserId,
  myDisplayName,
  membersByUserId,
}: Props) {
  const [messages, setMessages] = useState<RoomMessage[]>([]);
  // IDs from the initial fetch — these skip the wipe animation.
  const initialIdsRef = useRef<Set<string>>(new Set());
  const [draft, setDraft] = useState("");
  const [posting, setPosting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  // Auto toggle — when ON, your twin agent participates in the
  // autonomous loop. When OFF, your twin stays silent (you can still
  // post manually). Other imported agents (Aleksei, Anil, etc.) keep
  // chatting either way. Server-persisted per-user-per-group.
  const [autoMode, setAutoMode] = useState(true);
  const [autoBusy, setAutoBusy] = useState(false);
  // Live summary banner — topic + dynamic, regenerated by an LLM,
  // shared across all members via Realtime so when one person hits
  // Refresh, everyone sees the new blurb.
  const [summary, setSummary] = useState<{
    topic: string | null;
    dynamic: string | null;
    generated_at: string | null;
  }>({ topic: null, dynamic: null, generated_at: null });
  const [summaryBusy, setSummaryBusy] = useState(false);
  const scrollRef = useRef<HTMLDivElement | null>(null);
  const asideRef = useRef<HTMLElement | null>(null);
  const textareaRef = useRef<HTMLTextAreaElement | null>(null);
  // Initial-mount auto-scroll: snap to bottom on first message render
  // so opening the panel always lands at the latest line. Tracked via
  // ref because state updates would race the layout pass.
  const didInitialScrollRef = useRef(false);
  // "X new ↓" pill — tracks unread count when user has scrolled up.
  const [unreadCount, setUnreadCount] = useState(0);

  const myAgentIds = useMemo(
    () => new Set(myAgents.map((a) => a.id)),
    [myAgents],
  );

  console.log("[ROOM] WorldRoomChat render — open:", open, "worldGroupId:", worldGroupId);

  useEffect(() => {
    console.log("[ROOM] useEffect triggered — open:", open, "worldGroupId:", worldGroupId);
    if (!open) {
      console.log("[ROOM] open=false, skipping fetch");
      return;
    }
    let cancelled = false;
    (async () => {
      console.log("[ROOM] Fetching room data for group:", worldGroupId);
      try {
        const [res, autoRes, sumRes] = await Promise.all([
          apiGet<{ messages: RoomMessage[] }>(
            `/api/world-groups/${encodeURIComponent(worldGroupId)}/room`,
          ),
          apiGet<{ auto_enabled: boolean }>(
            `/api/world-groups/${encodeURIComponent(worldGroupId)}/auto`,
          ).catch(() => ({ auto_enabled: true })),
          apiGet<{
            topic: string | null;
            dynamic: string | null;
            generated_at: string | null;
          }>(
            `/api/world-groups/${encodeURIComponent(worldGroupId)}/room/summary`,
          ).catch(() => ({ topic: null, dynamic: null, generated_at: null })),
        ]);
        if (cancelled) return;
        console.log("[ROOM] Fetched", res.messages.length, "messages");
        initialIdsRef.current = new Set(res.messages.map((m) => m.id));
        setMessages(res.messages);
        setAutoMode(autoRes.auto_enabled);
        setSummary(sumRes);
      } catch (err) {
        console.error("[ROOM] Fetch error:", err);
        if (cancelled) return;
        setError(
          err instanceof ApiError ? `${err.status}: ${err.message}` : String(err),
        );
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [open, worldGroupId]);

  const refreshSummary = useCallback(async () => {
    if (summaryBusy) return;
    setSummaryBusy(true);
    try {
      const res = await apiPost<{
        topic: string | null;
        dynamic: string | null;
        generated_at?: string;
      }>(
        `/api/world-groups/${encodeURIComponent(worldGroupId)}/room/summary/refresh`,
        {},
      );
      setSummary({
        topic: res.topic,
        dynamic: res.dynamic,
        generated_at: res.generated_at ?? new Date().toISOString(),
      });
    } catch (err) {
      setError(
        err instanceof ApiError ? `${err.status}: ${err.message}` : String(err),
      );
    } finally {
      setSummaryBusy(false);
    }
  }, [worldGroupId, summaryBusy]);

  const toggleAuto = useCallback(async () => {
    if (autoBusy) return;
    const next = !autoMode;
    setAutoBusy(true);
    setAutoMode(next); // optimistic
    try {
      await apiPatch(
        `/api/world-groups/${encodeURIComponent(worldGroupId)}/auto`,
        { enabled: next },
      );
    } catch (err) {
      setAutoMode(!next); // rollback
      setError(
        err instanceof ApiError ? `${err.status}: ${err.message}` : String(err),
      );
    } finally {
      setAutoBusy(false);
    }
  }, [autoBusy, autoMode, worldGroupId]);

  // Poll for new room messages + summary updates (replaces the old
  // supabase realtime channel). The initial load effect above seeds the
  // list; this keeps it live while the panel is open and the tab visible.
  useEffect(() => {
    if (!open) return;
    let cancelled = false;
    const poll = async () => {
      try {
        const [res, sumRes] = await Promise.all([
          apiGet<{ messages: RoomMessage[] }>(
            `/api/world-groups/${encodeURIComponent(worldGroupId)}/room`,
          ),
          apiGet<{
            topic: string | null;
            dynamic: string | null;
            generated_at: string | null;
          }>(
            `/api/world-groups/${encodeURIComponent(worldGroupId)}/room/summary`,
          ).catch(() => null),
        ]);
        if (cancelled) return;
        setMessages((prev) => {
          const known = new Set(prev.map((x) => x.id));
          const incoming = res.messages.filter((m) => !known.has(m.id));
          if (incoming.length === 0) return prev;
          for (const m of incoming) {
            if (
              myDisplayName &&
              m.user_id !== myUserId &&
              m.body.toLowerCase().includes(`@${myDisplayName.toLowerCase()}`)
            ) {
              try {
                new Audio("/sfx/human-notification.mp3").play();
              } catch {}
            }
          }
          const merged = [...prev, ...incoming];
          merged.sort((a, b) => a.seq - b.seq);
          return merged.slice(-200);
        });
        if (sumRes && (sumRes.topic || sumRes.dynamic)) {
          setSummary({
            topic: sumRes.topic ?? null,
            dynamic: sumRes.dynamic ?? null,
            generated_at: sumRes.generated_at ?? null,
          });
        }
      } catch {
        /* ignore transient poll errors */
      }
    };
    const iv = setInterval(() => {
      if (!cancelled && document.visibilityState === "visible") void poll();
    }, 3000);
    return () => {
      cancelled = true;
      clearInterval(iv);
    };
  }, [open, worldGroupId, myDisplayName, myUserId]);

  // Reset scroll bookkeeping when the panel reopens or switches groups.
  useEffect(() => {
    didInitialScrollRef.current = false;
    setUnreadCount(0);
  }, [open, worldGroupId]);

  // Initial-mount snap to bottom + auto-stick when near-bottom +
  // unread-count when user has scrolled up to read history.
  useEffect(() => {
    const el = scrollRef.current;
    if (!el) return;
    if (!didInitialScrollRef.current && messages.length > 0) {
      // Run after layout has measured the new rows.
      requestAnimationFrame(() => {
        el.scrollTop = el.scrollHeight;
        didInitialScrollRef.current = true;
        setUnreadCount(0);
      });
      return;
    }
    const nearBottom =
      el.scrollHeight - el.scrollTop - el.clientHeight < 80;
    if (nearBottom) {
      el.scrollTop = el.scrollHeight;
      setUnreadCount(0);
    } else {
      setUnreadCount((c) => c + 1);
    }
  }, [messages]);

  // Detect when the user manually scrolls down to bottom — clear
  // unread without forcing them down.
  const onScroll = () => {
    const el = scrollRef.current;
    if (!el) return;
    const nearBottom =
      el.scrollHeight - el.scrollTop - el.clientHeight < 40;
    if (nearBottom && unreadCount > 0) setUnreadCount(0);
  };

  const jumpToBottom = () => {
    const el = scrollRef.current;
    if (!el) return;
    el.scrollTop = el.scrollHeight;
    setUnreadCount(0);
  };

  const send = useCallback(async () => {
    const body = draft.trim();
    if (!body || posting) return;
    setPosting(true);
    setError(null);
    try {
      await apiPost<{ message: RoomMessage }>(
        `/api/world-groups/${encodeURIComponent(worldGroupId)}/room/post`,
        // Always post as yourself — no ventriloquising other agents.
        { body, agent_id: null },
      );
      posthog.capture("room_message_sent", { world_group_id: worldGroupId, world_group_name: worldGroupName });
      setDraft("");
    } catch (err) {
      setError(
        err instanceof ApiError ? `${err.status}: ${err.message}` : String(err),
      );
    } finally {
      setPosting(false);
    }
  }, [draft, posting, worldGroupId]);

  // Click-outside-the-panel blurs the textarea so the player can move
  // again. Browsers don't auto-blur when you click a non-focusable
  // element (the Phaser canvas has no tabindex), so the textarea
  // would silently keep focus and the focus-check in WorldScene's
  // getCombinedInput would think you're still typing forever.
  useEffect(() => {
    if (!open) return;
    const handler = (e: MouseEvent | PointerEvent) => {
      const aside = asideRef.current;
      const textarea = textareaRef.current;
      if (!aside || !textarea) return;
      // Only blur if focus is currently on the textarea AND the
      // pointer landed outside the panel.
      if (document.activeElement !== textarea) return;
      const target = e.target as Node | null;
      if (target && aside.contains(target)) return;
      textarea.blur();
    };
    document.addEventListener("pointerdown", handler);
    return () => document.removeEventListener("pointerdown", handler);
  }, [open]);

  const onKeyDown = (e: React.KeyboardEvent<HTMLTextAreaElement>) => {
    // Stop the native event from bubbling to Phaser's window-level
    // keyboard listener — guarantees the player doesn't move and
    // chat keys don't fire while you're typing, regardless of
    // Phaser's capture/preventDefault settings.
    e.stopPropagation();
    e.nativeEvent.stopImmediatePropagation();
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      send();
    }
  };

  if (!open) {
    console.log("[ROOM] Returning null — open is false");
    return null;
  }
  console.log("[ROOM] Rendering panel — open:", open, "messages:", messages.length, "error:", error);

  return (
    <aside
      ref={asideRef}
      role="region"
      aria-label="Room chat"
      className="fixed inset-0 z-40 flex w-full flex-col overflow-hidden border-[#1f2a3c] bg-[rgba(246,244,234,0.99)] text-[#1f2a3c] sm:inset-y-4 sm:right-4 sm:left-auto sm:w-[min(440px,calc(100vw-1.5rem))] sm:border-[3px] sm:shadow-[6px_6px_0_#1f2a3c]"
    >
      <header className="flex items-center justify-between border-b-[3px] border-[#1f2a3c] bg-[#dcecf4] px-3 py-2">
        <div className="min-w-0">
          <p className="font-mono text-[10px] font-bold uppercase tracking-[0.2em] text-[#1f2a3c]">
            Room · {worldGroupName}
          </p>
          <p className="font-mono text-[9px] uppercase tracking-[0.16em] text-[#5a6d80]">
            {messages.length} lines · live
          </p>
        </div>
        <button
          type="button"
          onClick={onClose}
          className="border-[3px] border-[#1f2a3c] bg-[#f6f4ea] px-2 py-0.5 font-mono text-[10px] font-bold uppercase shadow-[2px_2px_0_#1f2a3c]"
        >
          Close
        </button>
      </header>

      <SummaryBanner
        topic={summary.topic}
        dynamic={summary.dynamic}
        generatedAt={summary.generated_at}
        busy={summaryBusy}
        onRefresh={refreshSummary}
      />

      {error && (
        <div className="mx-2 mt-2 border-[3px] border-[#1f2a3c] bg-[#f7ddd7] px-2 py-1 font-mono text-[9px] uppercase tracking-wider text-[#6d2d24] shadow-[2px_2px_0_#1f2a3c]">
          {error}
        </div>
      )}

      <div
        ref={scrollRef}
        onScroll={onScroll}
        className="relative flex-1 overflow-y-auto overflow-x-hidden px-2 py-1 font-mono"
        style={{ scrollBehavior: "smooth" }}
      >
        {messages.length === 0 ? (
          <p className="px-2 py-3 text-[10px] uppercase tracking-wider text-[#7f8b98]">
            The room is quiet. Say hi.
          </p>
        ) : (
          <ol className="space-y-[1px]">
            {messages.map((m) => {
              const isMyOwn = m.user_id !== null && m.user_id === myUserId;
              const isMyAgent = !!(m.agent_id && myAgentIds.has(m.agent_id));
              let resolvedName: string;
              if (isMyOwn) {
                resolvedName = myDisplayName || "You";
              } else if (m.agent_id) {
                resolvedName =
                  agentsById.get(m.agent_id)?.display_name ||
                  m.speaker_name ||
                  "Agent";
              } else if (m.user_id) {
                resolvedName =
                  membersByUserId.get(m.user_id) ||
                  m.speaker_name ||
                  "Someone";
              } else {
                resolvedName = m.speaker_name || "Someone";
              }
              return (
                <RoomLine
                  key={m.id}
                  m={m}
                  name={resolvedName}
                  isMyAgent={isMyAgent}
                  isMyOwn={isMyOwn}
                  animate={!initialIdsRef.current.has(m.id)}
                />
              );
            })}
          </ol>
        )}
      </div>

      {unreadCount > 0 && (
        <button
          type="button"
          onClick={jumpToBottom}
          className="absolute bottom-[88px] left-1/2 -translate-x-1/2 border-[3px] border-[#1f2a3c] bg-[#1f2a3c] px-3 py-1 font-mono text-[10px] font-bold uppercase tracking-[0.16em] text-[#fffaf0] shadow-[3px_3px_0_rgba(31,42,60,0.4)] hover:bg-[#3a4a60]"
        >
          {unreadCount} new ↓
        </button>
      )}

      <footer className="border-t-[3px] border-[#1f2a3c] bg-[#fffaf0] px-2 py-2">
        <div className="mb-1.5 flex items-center justify-between gap-2">
          <span className="font-mono text-[9px] font-bold uppercase tracking-[0.16em] text-[#637387]">
            Speaking as{" "}
            <span className="text-[#1f2a3c]">
              {myDisplayName || "Yourself"}
            </span>
          </span>
          <button
            type="button"
            onClick={toggleAuto}
            disabled={autoBusy}
            aria-pressed={autoMode}
            title={
              autoMode
                ? "Your twin will autospeak in this room"
                : "Your twin is silent — you'll only post when you type"
            }
            className={
              "flex items-center gap-1 border-[3px] border-[#1f2a3c] px-1.5 py-0.5 font-mono text-[9px] font-bold uppercase tracking-[0.16em] shadow-[2px_2px_0_#1f2a3c] disabled:opacity-60 " +
              (autoMode
                ? "bg-[#d6f4d6] text-[#1f2a3c]"
                : "bg-[#f6f4ea] text-[#7f8b98]")
            }
          >
            <span
              className={
                "inline-block h-2 w-2 rounded-full " +
                (autoMode ? "bg-[#2f6e2c]" : "bg-[#9aa6b1]")
              }
            />
            Auto · {autoMode ? "ON" : "OFF"}
          </button>
        </div>
        <div className="flex items-end gap-2">
          <textarea
            ref={textareaRef}
            value={draft}
            onChange={(e) => setDraft(e.target.value)}
            onKeyDown={onKeyDown}
            rows={1}
            maxLength={500}
            placeholder="Type — Enter to send"
            className="flex-1 resize-none border-[3px] border-[#1f2a3c] bg-[#fffaf0] px-2 py-1 font-mono text-[12px] shadow-[2px_2px_0_#1f2a3c] outline-none"
          />
          <button
            type="button"
            onClick={send}
            disabled={!draft.trim() || posting}
            className="border-[3px] border-[#1f2a3c] bg-[#ffe17d] px-2 py-1 font-mono text-[10px] font-bold uppercase text-[#1f2a3c] shadow-[2px_2px_0_#1f2a3c] disabled:cursor-not-allowed disabled:opacity-60"
          >
            {posting ? "…" : "Send"}
          </button>
        </div>
      </footer>
    </aside>
  );
}

function SummaryBanner({
  topic,
  dynamic,
  generatedAt,
  busy,
  onRefresh,
}: {
  topic: string | null;
  dynamic: string | null;
  generatedAt: string | null;
  busy: boolean;
  onRefresh: () => void;
}) {
  const isEmpty = !topic && !dynamic;
  const ageLabel = useMemo(() => {
    if (!generatedAt) return "";
    const sec = Math.max(
      1,
      Math.floor((Date.now() - new Date(generatedAt).getTime()) / 1000),
    );
    if (sec < 60) return `${sec}s ago`;
    if (sec < 3600) return `${Math.round(sec / 60)}m ago`;
    return `${Math.round(sec / 3600)}h ago`;
  }, [generatedAt]);
  return (
    <div className="border-b-[3px] border-[#1f2a3c] bg-[#fffaf0] px-3 py-2">
      <div className="flex items-start justify-between gap-2">
        <div className="min-w-0">
          <p className="font-mono text-[9px] font-bold uppercase tracking-[0.18em] text-[#637387]">
            Live summary
            {ageLabel && (
              <span className="ml-2 text-[#9aa6b1]">· {ageLabel}</span>
            )}
          </p>
          {isEmpty ? (
            <p className="mt-0.5 font-mono text-[10px] uppercase tracking-wider text-[#7f8b98]">
              No summary yet — tap refresh to generate.
            </p>
          ) : (
            <>
              {topic && (
                <p className="mt-0.5 truncate font-mono text-[12px] font-bold uppercase tracking-[0.06em] text-[#1f2a3c]">
                  {topic}
                </p>
              )}
              {dynamic && (
                <p className="mt-0.5 text-[11px] italic leading-snug text-[#425166]">
                  {dynamic}
                </p>
              )}
            </>
          )}
        </div>
        <button
          type="button"
          onClick={onRefresh}
          disabled={busy}
          aria-label="Refresh summary"
          className="shrink-0 border-[3px] border-[#1f2a3c] bg-[#f6f4ea] px-2 py-1 font-mono text-[10px] font-bold uppercase shadow-[2px_2px_0_#1f2a3c] disabled:opacity-60"
        >
          {busy ? "…" : "↻"}
        </button>
      </div>
    </div>
  );
}

function RoomLine({
  m,
  name,
  isMyAgent,
  isMyOwn,
  animate,
}: {
  m: RoomMessage;
  name: string;
  isMyAgent: boolean;
  isMyOwn: boolean;
  animate: boolean;
}) {
  const color = isMyOwn ? "text-[#1f2a3c]" : nameColor(name);

  let badge: { text: string; cls: string } | null = null;
  if (isMyOwn) {
    badge = { text: "you", cls: "bg-[#ffe17d] text-[#1f2a3c]" };
  } else if (m.agent_id && !m.user_id) {
    // Any autonomous agent line gets `auto`. The cream-warm variant
    // (`auto · you`) keeps a visual cue when it's *your* twin/agent
    // speaking on your behalf vs someone else's autonomous agent.
    badge = isMyAgent
      ? { text: "auto · you", cls: "bg-[#fff3cd] text-[#854f1f]" }
      : { text: "auto", cls: "bg-[#e8e4d9] text-[#5a6275]" };
  }

  const rowBg = isMyOwn ? "bg-[#fff8db]" : isMyAgent ? "bg-[#fffaeb]" : "";

  return (
    <li className={(animate ? "room-msg-in " : "") + "px-1.5 py-0.5 leading-[1.35] " + rowBg}>
      <span className={`text-[12px] font-bold ${color}`}>{name}</span>
      {badge && (
        <span
          className={`mx-1 inline-block px-1 align-baseline text-[9px] font-bold uppercase tracking-[0.12em] ${badge.cls}`}
        >
          {badge.text}
        </span>
      )}
      <span className="text-[#3d4a5c]">: </span>
      <span className="text-[12px] text-[#1f2a3c]">{m.body}</span>
    </li>
  );
}
